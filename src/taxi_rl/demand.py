"""Ride-request demand model.

Requests are generated by a non-homogeneous Poisson process. Pickups cluster
around real Midtown hotspots whose intensity follows a daily profile (commuter
hubs spike at AM rush, the theatre district at night, offices at PM rush).
Dropoffs are drawn from a separate, time-dependent destination mix, so where a
trip *ends* matters — a core idea the agent has to learn.

Fares follow the NYC yellow-cab meter (simplified):
    $3.00 flag drop + $3.50 / mile + $0.35 / minute (+ $1 PM-peak surcharge)

Two features make the decision problem non-trivial (and realistic):

* **Surge events** — localised, temporary demand spikes (a show letting out,
  a rainstorm, a stalled subway line). A zone's request rate and fares are
  multiplied by ``surge`` which decays with a ~20 min half-life.
* **Airport runs** — a share of riders want LaGuardia. The fare is big, but the
  taxi leaves Midtown: the outbound leg and the return (maybe with a rider from
  the airport queue, maybe empty) both depend heavily on traffic, so the same
  trip is great at 2 AM and terrible at 5:30 PM.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .graph import RoadGraph

# name, lat, lon, profile
HOTSPOTS: list[tuple[str, float, float, str]] = [
    ("Penn Station", 40.7506, -73.9935, "commuter"),
    ("Grand Central", 40.7527, -73.9772, "commuter"),
    ("Port Authority", 40.7569, -73.9903, "commuter"),
    ("Times Square", 40.7580, -73.9855, "nightlife"),
    ("Bryant Park offices", 40.7536, -73.9832, "office"),
    ("Madison Sq Garden", 40.7505, -73.9934, "events"),
    ("Hudson Yards", 40.7536, -74.0007, "office"),
    ("Flatiron / Union Sq", 40.7411, -73.9897, "nightlife"),
    ("Murray Hill homes", 40.7479, -73.9757, "residential"),
    ("Chelsea homes", 40.7465, -74.0014, "residential"),
    ("Rockefeller Center", 40.7587, -73.9787, "office"),
]


def _profile(kind: str, h: np.ndarray) -> np.ndarray:
    g = lambda mu, s: np.exp(-((h - mu) ** 2) / (2 * s**2))
    if kind == "commuter":
        return 0.25 + 1.6 * g(8.0, 1.2) + 1.3 * g(18.0, 1.4)
    if kind == "office":
        return 0.15 + 0.6 * g(9.0, 1.0) + 0.6 * g(13.0, 1.5) + 1.4 * g(18.0, 1.3)
    if kind == "nightlife":
        return 0.25 + 0.6 * g(19.0, 1.5) + 1.8 * g(23.0, 1.8) + 1.0 * g(1.0, 1.5)
    if kind == "events":
        return 0.2 + 1.6 * g(22.5, 0.8)
    if kind == "residential":
        return 0.3 + 1.4 * g(8.0, 1.5) + 0.4 * g(20.0, 2.0)
    return np.ones_like(h)


def _dest_profile(kind: str, h: np.ndarray) -> np.ndarray:
    """Attractiveness as a *destination* — roughly mirrors the pickup profile."""
    g = lambda mu, s: np.exp(-((h - mu) ** 2) / (2 * s**2))
    if kind == "commuter":
        return 0.4 + 1.6 * g(18.0, 1.5)
    if kind == "office":
        return 0.2 + 1.8 * g(8.5, 1.3) + 0.4 * g(13.0, 1.5)
    if kind == "nightlife":
        return 0.3 + 1.4 * g(20.0, 2.0)
    if kind == "events":
        return 0.2 + 1.2 * g(19.0, 0.8)
    if kind == "residential":
        return 0.4 + 1.5 * g(19.0, 2.0) + 1.2 * g(0.5, 2.0)
    return np.ones_like(h)


@dataclass
class Request:
    rid: int
    pickup: int
    dropoff: int
    t_request: float  # sim seconds
    patience_s: float
    hotspot: int
    airport: bool = False
    surge: float = 1.0

    @property
    def expires(self) -> float:
        return self.t_request + self.patience_s


def fare_usd(distance_m: float, duration_s: float, hour: float) -> float:
    miles = distance_m / 1609.34
    surcharge = 1.0 if 16 <= (hour % 24) < 20 else 0.0
    return 3.0 + 3.5 * miles + 0.35 * (duration_s / 60.0) + surcharge


@dataclass
class SurgeEvent:
    zone: int
    t0: float
    peak: float  # multiplier at t0, e.g. 1.8
    half_life_s: float = 1200.0
    horizon_s: float = 3600.0

    def at(self, t: float) -> float:
        if t < self.t0 or t > self.t0 + self.horizon_s:
            return 0.0
        return (self.peak - 1.0) * 0.5 ** ((t - self.t0) / self.half_life_s)


def surge_events_rate(hour: float) -> float:
    """Expected surge events per hour across the whole area."""
    h = hour % 24
    return 0.5 + 1.0 * np.exp(-((h - 18) ** 2) / 4) + 1.2 * np.exp(-((h - 22.5) ** 2) / 2)


def airport_prob(hour: float, kind: str) -> float:
    h = hour % 24
    base = 0.05 + 0.05 * np.exp(-((h - 6) ** 2) / 4) + 0.04 * np.exp(-((h - 15) ** 2) / 6)
    if kind in ("commuter", "office"):
        base *= 1.6
    return float(base)


AIRPORT = {"name": "LaGuardia (LGA)", "lat": 40.7769, "lon": -73.8740, "exit": (40.7465, -73.9730),
           "leg_km": 13.0, "leg_freeflow_s": 1080.0, "surcharge": 5.0,
           "return_fare_prob": 0.35, "queue_wait_s": (600.0, 1800.0)}


class DemandModel:
    def __init__(
        self,
        graph: RoadGraph,
        base_rate_per_min: float = 0.35,
        spread_km: float = 0.25,
        patience_range_s: tuple[float, float] = (240.0, 600.0),
        min_trip_m: float = 400.0,
    ):
        self.g = graph
        self.base_rate = base_rate_per_min
        self.patience_range = patience_range_s
        self.min_trip_m = min_trip_m
        xy = graph.xy_km()
        self._xy = xy
        lat0, lon0 = float(graph.lat.min()), float(graph.lon.min())
        kx = 111.32 * np.cos(np.radians(float(graph.lat.mean())))
        self.hotspots = []
        weights = []
        for name, la, lo, kind in HOTSPOTS:
            hxy = np.array([(lo - lon0) * kx, (la - lat0) * 110.57])
            d2 = ((xy - hxy) ** 2).sum(1)
            if d2.min() > 0.6**2:  # hotspot outside this graph
                continue
            w = np.exp(-d2 / (2 * spread_km**2))
            weights.append(w / w.sum())
            self.hotspots.append((name, la, lo, kind))
        if not self.hotspots:  # e.g. synthetic grid: invent 5 hotspots on nodes
            rng = np.random.default_rng(0)
            kinds = ["commuter", "office", "nightlife", "residential", "events"]
            for i, n in enumerate(rng.choice(graph.n_nodes, size=5, replace=False)):
                d2 = ((xy - xy[n]) ** 2).sum(1)
                w = np.exp(-d2 / (2 * spread_km**2))
                weights.append(w / w.sum())
                self.hotspots.append((f"hub-{i}", graph.lat[n], graph.lon[n], kinds[i]))
        self.node_weights = np.stack(weights)  # (H, N)
        self.kinds = [h[3] for h in self.hotspots]
        # Background demand everywhere (uniform), so no area is totally dead.
        self.background = 0.15

    def hotspot_rates(self, hour: float) -> np.ndarray:
        """Per-hotspot request rate (per minute) at ``hour`` (cached per minute of day)."""
        key = int((hour % 24) * 60)
        cache = self.__dict__.setdefault("_rate_cache", {})
        if key not in cache:
            cache[key] = self._hotspot_rates(key / 60.0)
        return cache[key]

    def _hotspot_rates(self, hour: float) -> np.ndarray:
        h = np.array([hour % 24])
        raw = np.array([_profile(k, h)[0] for k in self.kinds])
        return self.base_rate * raw / len(self.kinds) * 2.0

    def dest_weights(self, hour: float) -> np.ndarray:
        key = int((hour % 24) * 60)
        cache = self.__dict__.setdefault("_dest_cache", {})
        if key not in cache:
            cache[key] = self._dest_weights(key / 60.0)
        return cache[key]

    def _dest_weights(self, hour: float) -> np.ndarray:
        h = np.array([hour % 24])
        raw = np.array([_dest_profile(k, h)[0] for k in self.kinds])
        return raw / raw.sum()

    def node_pickup_intensity(self, hour: float) -> np.ndarray:
        """(N,) expected requests / min originating at each node."""
        r = self.hotspot_rates(hour)
        bg = self.background * self.base_rate / self.g.n_nodes
        return r @ self.node_weights + bg

    def sample(
        self, rng: np.random.Generator, t0: float, t1: float, hour_of: callable, next_id: int
    ) -> list[Request]:
        """Sample requests arriving in sim-time window [t0, t1)."""
        out: list[Request] = []
        if t1 <= t0:
            return out
        # Piecewise-constant thinning at 1-minute resolution.
        t = t0
        while t < t1:
            dt = min(60.0, t1 - t)
            hour = hour_of(t)
            rates = self.hotspot_rates(hour)
            bg_rate = self.background * self.base_rate
            lam = (rates.sum() + bg_rate) * dt / 60.0
            k = rng.poisson(lam)
            if k:
                p = np.append(rates, bg_rate)
                p = p / p.sum()
                dw = self.dest_weights(hour)
                for _ in range(k):
                    src = rng.choice(len(p), p=p)
                    if src == len(rates):
                        pickup = int(rng.integers(self.g.n_nodes))
                    else:
                        pickup = int(rng.choice(self.g.n_nodes, p=self.node_weights[src]))
                    for _try in range(10):
                        if rng.random() < 0.25:
                            dropoff = int(rng.integers(self.g.n_nodes))
                        else:
                            d = rng.choice(len(dw), p=dw)
                            dropoff = int(rng.choice(self.g.n_nodes, p=self.node_weights[d]))
                        if np.linalg.norm(self._xy[pickup] - self._xy[dropoff]) * 1000 >= self.min_trip_m:
                            break
                    out.append(
                        Request(
                            rid=next_id + len(out),
                            pickup=pickup,
                            dropoff=dropoff,
                            t_request=t + rng.random() * dt,
                            patience_s=float(rng.uniform(*self.patience_range)),
                            hotspot=int(src),
                        )
                    )
            t += dt
        out.sort(key=lambda r: r.t_request)
        for i, r in enumerate(out):
            r.rid = next_id + i
        return out

    # ----------------------------------------------------------- full shift
    def sample_shift(
        self, rng: np.random.Generator, t0: float, t1: float, hour_of, zone_labels: np.ndarray,
        n_zones: int,
    ) -> tuple[list[Request], list[SurgeEvent]]:
        """Base demand + surge events (extra riders, higher fares) + airport riders."""
        base = self.sample(rng, t0, t1, hour_of, 0)
        # Surge events
        events: list[SurgeEvent] = []
        t = t0
        while t < t1:
            lam = surge_events_rate(hour_of(t)) / 60.0  # per minute
            t += rng.exponential(1.0 / lam) * 60.0
            if t >= t1:
                break
            events.append(SurgeEvent(zone=int(rng.integers(n_zones)), t0=t,
                                     peak=float(rng.uniform(1.4, 2.2))))
        # Extra riders generated by each surge (inside the zone)
        extra: list[Request] = []
        for ev in events:
            nodes = np.flatnonzero(zone_labels == ev.zone)
            if len(nodes) == 0:
                continue
            zone_rate = self.node_pickup_intensity(hour_of(ev.t0))[nodes].sum()  # per min
            mean_extra = (ev.peak - 1.0) * zone_rate * (ev.half_life_s / 60.0) / np.log(2) * 1.5
            for _ in range(rng.poisson(mean_extra)):
                # arrival times follow the exponential decay of the surge
                tr = ev.t0 + rng.exponential(ev.half_life_s / np.log(2))
                if tr >= t1:
                    continue
                pickup = int(rng.choice(nodes))
                dropoff = int(rng.integers(self.g.n_nodes))
                extra.append(Request(rid=0, pickup=pickup, dropoff=dropoff, t_request=float(tr),
                                     patience_s=float(rng.uniform(*self.patience_range)), hotspot=-1))
        reqs = sorted(base + extra, key=lambda r: r.t_request)
        for i, r in enumerate(reqs):
            r.rid = i
            z = int(zone_labels[r.pickup])
            r.surge = 1.0 + sum(e.at(r.t_request) for e in events if e.zone == z)
            kind = self.kinds[r.hotspot] if 0 <= r.hotspot < len(self.kinds) else "background"
            r.airport = bool(rng.random() < airport_prob(hour_of(r.t_request), kind))
        return reqs, events
